#!/usr/bin/env python3
"""Writes packages/quranlab_tajweedformer/test/fixtures/errors_40_cases.g.dart from test/fixtures/errors_40.json (the
contract's errors_40 vector rows the plugin carries): the cause rows and the codes that carry no cause, as Dart
constants, because a test in a browser (test/web_host_test.dart) cannot read a file. test/plugin_test.dart checks
that the Dart file is this script's output for the JSON in the repository, so the two never drift.

  python3 tool/gen_errors_40_cases.py           write it
  python3 tool/gen_errors_40_cases.py --check   exit 1 when it differs

Why (Flutter 4.1.0): on the web the plugin's own layer between the web SDK and the app is webError() in
lib/src/web/web_host.dart (the SDK's thrown error to a TajweedError); replaying the contract's cause rows through it
is the web's error parity check. The cause itself is made by the web SDK, which replays the same vector in its own CI.
"""
import json
import sys
from pathlib import Path

PKG = Path(__file__).resolve().parent.parent / "packages/quranlab_tajweedformer"
SRC = PKG / "test/fixtures/errors_40.json"
OUT = PKG / "test/fixtures/errors_40_cases.g.dart"

# the vector's snake_case cause fields and the web SDK's errorCause names (web/index.d.ts TajweedErrorCause)
FIELDS = [("stage", "stage"), ("reason", "reason"), ("http_status", "httpStatus"), ("error_name", "errorName"),
          ("error_code", "errorCode"), ("needs", "needs")]


def dart(v):
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    return "'" + str(v).replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$") + "'"


def render():
    d = json.loads(SRC.read_text(encoding="utf-8"))
    out = ["// GENERATED by tool/gen_errors_40_cases.py from errors_40.json; do not edit. See that script for why.",
           "",
           "/// The vector's cause rows: the code the app gets and the cause its error carries (web field names).",
           "const errors40Causes = <({String label, String code, Map<String, Object?>? cause})>["]
    for row in d["causes"]:
        if row.get("cause") is None:  # a code that only says the API was used wrongly: no cause
            out.append(f"  (label: {dart(row['label'])}, code: {dart(row['code'])}, cause: null),")
            continue
        cause = {web: row["cause"].get(key) for key, web in FIELDS if row["cause"].get(key) is not None}
        body = ", ".join(f"{dart(k)}: {dart(v)}" for k, v in cause.items())
        out.append(f"  (label: {dart(row['label'])}, code: {dart(row['code'])}, cause: {{{body}}}),")
    out.append("];")
    out.append("")
    out.append("/// The codes that only say the API was used wrongly: they carry no cause.")
    out.append("const errors40CodesNotReported = <String>[" + ", ".join(dart(c) for c in d["codes_not_reported"]) + "];")
    out.append("")
    return "\n".join(out)


def main():
    text = render()
    if "--check" in sys.argv:
        have = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if have != text:
            print(f"{OUT.relative_to(PKG.parent.parent)} is not the output of tool/gen_errors_40_cases.py; run it")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(PKG.parent.parent)}: {text.count('(label:')} cause rows")
    return 0


if __name__ == "__main__":
    sys.exit(main())
